    fn headers_compile_and_match_rust_n1() {
        headers_compile::<1>();
    }

    #[test]
    fn headers_compile_and_match_rust_n4() {
        headers_compile::<4>();
    }

    #[test]
    fn headers_compile_and_match_rust_n64() {
        headers_compile::<64>();
    }

    #[test]
    fn the_c_header_carries_n_and_depth() {
        for n in [1, 4, 64] {
            let h = c_header(n, 4);
            assert!(h.contains(&format!("#define KMR_N {n}\n")));
            assert!(h.contains("#define KMR_HISTORY_DEPTH 4\n"));
            assert!(h.contains("#define KMR_AGE_NONE UINT32_MAX\n"));
            assert!(h.contains("    float q[KMR_N];\n"));
            assert!(h.contains("    uint64_t envelope;\n"));
            assert!(h.contains("static inline void kmr_set_tau(kmr_write_buf *w, unsigned i"));
            assert!(h.contains("KMR_CONTINUE = 0, KMR_SHUTDOWN = 1, KMR_EMERGENCY_STOP = 2"));
        }
    }

    #[test]
    fn the_abi_file_carries_n_and_depth() {
        let abi = abi_rs(10, 4);
        assert!(abi.contains("const FFI_N: usize = 10;"));
        assert!(abi.contains("const FFI_DEPTH: usize = 4;"));
    }

    #[test]
    fn no_engine_item_crosses() {
        let banned = [
            "Robot",
            "robot",
            "run",
            "builder",
            "Builder",
            "PreInit",
            "Init",
            "PostInit",
            "First",
            "EachTick",
            "Last",
            "Schedule",
            "Signal",
            "signal",
            "Bus",
            "Hal",
            "hal",
            "HAL",
            "adapter_t",
            "kmr_shutdown",
            "kmr_emergency_stop",
        ];
        let headers = [c_header(4, 4), cpp_header()];
        for h in &headers {
            let words: Vec<&str> = h
                .split(|c: char| !(c.is_ascii_alphanumeric() || c == '_'))
                .collect();
            for word in banned {
                assert!(!words.contains(&word), "header names `{word}`");
            }
        }
    }

    #[test]
    fn sources_split_by_language() {
        let (c, cpp) = split(&["a.c", "b.cpp", "c.cc", "d.cxx"]).expect("all known");
        assert_eq!(c, ["a.c"]);
        assert_eq!(cpp, ["b.cpp", "c.cc", "d.cxx"]);
        let err = split(&["a.c", "swing.rs"]).expect_err("not C");
        assert!(err.to_string().contains("swing.rs"));
    }

    #[test]
    fn compile_outside_a_build_script_is_an_error() {
        let err = Build::new(4, 4)
            .compile(&["swing.c"])
            .expect_err("no OUT_DIR");
        assert!(err.to_string().contains("OUT_DIR"));
    }
